"""
   Temporary work-around for mv_batch.sh due to issues with Chrome used by
   Plotly and kaleido when generating static plots.

   The Java MVBatch code will fail due to the Chrome error, but the data and YAML
   config files created by MVBatch can be used to invoke the corresponding
   METplotpy plot code.

"""

# Mapping the R templates in MVBatch to corresponding METplotpy plots
R2Python: dict = {
    'rhist.R_tmpl': 'histogram/rel_hist.py',
    'phist.R_tmpl': 'histogram/prob_hist.py',
    'relp.R_tmpl': 'histogram/rel_hist.py',
    'roc.R_tmpl':'roc_diagram/roc_diagram.py',
    'rely.R_tmpl':'reliability_diagram/reliability.py',
    'eclv.R_tmpl':'eclv/eclv.py',
    'taylor.R_tmpl':'taylor_diagram/taylor_diagram.py',
    'performance.R_tmpl':'performance_diagram/performance_diagram.py',
    'ens_ss.R_tmpl':'ens_ss/ens_ss.py',
    'contour_plot.R_tmpl':'contour/contour.py',
    'series_plot.R_tmpl':'line/line.py',
    }


def parse_batch_xml(batch_configfile: str ):
    '''
       Parse the XML batch file for the location of the YAML and data files created
       by METviewer MVBatch.java, the directory where plots are to be saved,
       the template to determine which METplotpy plot module to invoke, the
       execution type (to verify that Python is requested for plot generation
       vs Rscript)

       Args:
           @param batch_configfile:  The full path to the XML batchfile input to the
                        mv_batch.sh script
      Returns:
           @param plotting_params: A named tuple containing the information needed
                        to invoke the appropriate METplotpy plotting module.

    '''

    # named tuple with parameters needed to plot using METplotpy
    PlotParams = namedtuple('PlotParams', "plots_dir data_dir  plot_type execution_type, requested_plots")

    try:
        parser = etree.XMLParser(remove_comments=True, resolve_entities=False)
        tree = etree.parse(batch_configfile, parser=parser)
        root = tree.getroot()

        parsed_info = {}
        parsed_info:dict = get_all_template_vals(root)

        # parent element to the plots and data elements
        folders = root.xpath('folders')

        # location for saving plots
        plots_dir = folders[0].xpath('plots')[0].text

        # location of the YAML config files and data generated by METviewer
        data_dir = folders[0].xpath('data')[0].text

        # parent element to the template and execution type elements
        plot_elem:list  = root.xpath('plot')

        # plot type e.g. series, ROC, histogram, etc.
        plot_type:str = plot_elem[0].xpath('template')[0].text

        # which method to use for plotting, Python or Rscript
        plotting_method:str  = plot_elem[0].xpath('execution_type')[0].text

        PlotVarStat = namedtuple('PlotVarStat', ['plot_identifier','var','stats_for_var'])


        # list of all the PlotVarStat named tuples
        all_var_stats = []

        #
        #  Retrieve all the variable and stat information that will be used to
        #  substitute into corresponding template values.
        #  Store this information into a named tuple that
        #  links the plot name attribute to the dep1_1 value and its
        #  corresponding dep1_1_stat1 values.
        #
        #  *NOTE:*
        #  Users are permitted to  create one or  more additional <plot> elements
        #  that inherit from a parent <plot> elem, or all plot child/sub elements can
        #  be contained under a single <plot> element.
        #
        for cur_plot in plot_elem:
            # if one or more child element(s) inherits from a parent <plot> element
            if cur_plot.attrib:
               plot_identifier = cur_plot.attrib['name']
            else:
              # no child <plot> elements, all plot content under one <plot> element
              plot_identifier = 'unnamed'

            for child in list(cur_plot.iter()):
                if child.tag == 'dep':
                    dep = child
                    # retrieve each fcst_var and its corresponding stat elements
                    for dchild in list(dep.iter()):
                        # retrieve any dep1_1 and dep1_1_stat
                        # information from the parsed_info dict (from
                        # <title> and <y_label>
                        if 'dep1_1' in parsed_info:
                           if dchild.tag == parsed_info['dep1_1']:
                              var = dchild.attrib['name']
                              temp_stats = []
                              for stat in list(dchild.iter()):
                                  if stat.tag == parsed_info['dep1_1_stat1']:
                                     statname = stat.text
                                     temp_stats.append(statname)
                                     # stats for the current key (fcst var name)
                              cur_plot_var_stat = PlotVarStat(plot_identifier, var, temp_stats)
                              all_var_stats.append(cur_plot_var_stat)

        # Build the data file names with all templates replaced with actual
        # values.
        data_filename_str = parsed_info['data_file']

        print(f"filename to create: {parsed_info['data_file']}")

        # substitute any <plot_fix> template values (ignore the dep1_1 and
        # dep1_1_stat1 templates for now
        dep1_pattern = r'.*(dep\d_\d)'
        dep1_stat_pattern = r'.*(dep\d_\d_stat\d)'
        datafile_pattern = r'data_file'
        for k in parsed_info.keys():
            dep1_match = re.match(dep1_pattern, k)
            dep1_stat_match = re.match(dep1_stat_pattern, k)
            datafile_match = re.match(datafile_pattern, k)

            # only substitute keys which are not data_filename, dep1_1, or
            # dep1_1_stat
            if not dep1_match and not dep1_stat_match and not datafile_match:
                temp_datafilename = data_filename_str.replace(k, parsed_info[k])

        # now substitute actual values for any dep1_1_stat  and dep1_1 template
        # names
        requested_filenames = []
        requested_plots = []
        stat_match = re.match(dep1_stat_pattern, temp_datafilename)
        var_match = re.match(dep1_pattern, temp_datafilename)

        # Match each var to its corresponding stats based on the plot_identifier
        if var_match and stat_match:
            var_tmpl = var_match.group(1)
            stats_tmpl = stat_match.group(1)

            # Replace each template value with an actual value
            for var_stat in all_var_stats:
                cur_var = var_stat.var
                stat_list = var_stat.stats_for_var
                for stat in stat_list:
                    temp = temp_datafilename.replace(stats_tmpl, stat)
                    temp = temp.replace(var_tmpl, cur_var)
                    requested_filenames.append(temp)
        else:
            # No templates used in filename
            requested_filenames.append(temp_datafilename)

        # Remove the curly braces and the .data extension
        for cur_plotname in requested_filenames:
            cur_plotname = cur_plotname.replace('{', '').replace('}','').replace('.data','')
            requested_plots.append(cur_plotname)

        # Incorporate this information into a named tuple
        plot_params:namedtuple() = PlotParams(plots_dir, data_dir, plot_type, plotting_method, requested_plots)


    except (RuntimeError, TypeError, NameError, KeyError):
        sys.exit("Parsing error(s) in batch xml file")

    return plot_params


def get_all_template_vals(root_elem: etree.Element) -> dict:
    """
        Retrieve all the template values, these are any values that correspond to
        filtering done in the METviewer UI such as setting the fixed values (via
        <plot_fix> in config file).

        Args:
            @param root_elem: the top/root of the xml etree
        Returns:
            results: a dictionary with the element name as key and corresponding value
            as value
    """

    results = {}
    data_file = root_elem.xpath('plot')[0].xpath('tmpl')[0].xpath('data_file')[0].text

    results['data_file'] = data_file

    # Get the mappings for the dep child elements to the fcst_var and stats
    title = root_elem.xpath('plot')[0].xpath('tmpl')[0].xpath('title')[0].text
    y1_label = root_elem.xpath('plot')[0].xpath('tmpl')[0].xpath('y1_label')[0].text

    title_tokens = title.rsplit('}')
    if len(title_tokens) > 1:
        for cur in title_tokens:
            pairs = cur.split('?')
            if len(pairs) == 2:
               dep_elem_str = pairs[0]
               val_elem_str = pairs[1]
               dep_elem = dep_elem_str.replace('{', '').strip()
               val_elem = val_elem_str.replace('map=', '').strip()
               results[dep_elem] = val_elem

    y1_tokens = y1_label.rsplit('}')
    num_tokens = len(y1_tokens)
    if num_tokens > 1:
       for cur in y1_tokens:
            if len(cur) > 0:
               pairs = cur.split("?")
               dep_elem_str = pairs[0]
               val_elem_str = pairs[1]
               dep_elem = dep_elem_str.replace('{' , '').strip()
               val_elem = val_elem_str.replace('map=', '').strip()

               if dep_elem not in results.keys():
                   # if the title doesn't have the stat value (y-axis) mapping add it
                   results[dep_elem] = val_elem

    # plot_fix element and children
    field_elems = root_elem.xpath('plot')[0].xpath('plot_fix')[0]
    for pfe in field_elems:
        k = pfe.attrib['name']
        # MODE has a <set> child of the <field>, others do not
        # check for the presence of this <set> child to retrieve the <val>
        if len(pfe.xpath('set')) > 0:
            all_field_children = list(pfe.iter())
            for fc in all_field_children:
                if fc.tag == 'val':
                    v= fc.text
                    results[k] = v

        else:
           v = pfe.xpath('val')[0].text
           results[k] = v
    print(f"results: {results}")
    return results


def make_plots(plotting_params:namedtuple, args) -> None:
    '''
        Generate the plots by invoking the appropriate plot module in METplotpy,
        using the appropriate Python executable.

        Args:
            @param plotting_params:  A named tuple containing the necessary
                                                   information for generating a METplotpy plot
       Returns:

           None- saves static plots as png files in output directory specified in the
                     xml batch file
    '''

    # unpack information from the named tuple:
    # PlotParams = namedtuple('PlotParams', "plots_dir data_dir  plot_type execution_type, requested_plots")
    plot_output_dir = plotting_params.plots_dir
    data_dir = plotting_params.data_dir
    method = plotting_params.execution_type
    plot_type = plotting_params.plot_type
    requested_plots:list = plotting_params.requested_plots

    # retrieve the other parameters used by mv_batch.sh/MVBatch.java to generate
    # plots
    mv_script_loc = args.loc
    python_executable = args.pyenv
    plotpy = args.plotpy

    # Create the paths for METplotpy plot code and set the PRE_LOAD_CHROME
    # env var to True to avoid loading Chrome at runtime
    plotpy_base = plotpy + '/metplotpy'
    plotpy_plots = plotpy_base + '/plots'
    os.environ['PRE_LOAD_CHROME'] = 'True'


    # Determine the METplotpy plot type and construct the full path to the plotting
    # module
    python_plot = plotpy_plots + '/' +  R2Python[plot_type]


    # Get the data and YAML files necessary for generating the
    # requested plot(s)
    data_dir_files = pathlib.Path(data_dir)
    requested_yaml = []
    for var_stat in requested_plots:
        expected_yaml = os.path.join(data_dir_files, var_stat+'.yaml')
        requested_yaml.append(expected_yaml)

    print(f"PYTHONPATH: \n {os.getenv('PYTHONPATH')}\n")
    for cur_yaml in requested_yaml:
        print(f"Plot using yaml config file: {cur_yaml}")
        # Create the command to create the plot
        command = str(python_executable) +" " +  python_plot + " " + str( cur_yaml)
        print(f" Running \n {command}\n")
        return_val = os.system(command )
        print(f"return value: {return_val}")

    return return_val


def main():

    # parse parameters passed in from mv_batch.sh
    parser = argparse.ArgumentParser(description='Parsing params from mv_batch.sh')
    parser.add_argument('--xml', required=True)
    parser.add_argument('--loc', required=True)
    parser.add_argument('--pyenv', required=True)
    parser.add_argument('--plotpy', required=True)

    args = parser.parse_args()



    # Extract necessary information from the batch XML file
    full_batch_xml:str = os.path.abspath(args.xml)
    plotting_params: namedtuple = parse_batch_xml(full_batch_xml)
    execution_type = str(plotting_params.execution_type)
    if execution_type.upper() == 'RSCRIPT':
        print("Rscript requested,  skip plotting via Python")
        sys.exit(0)
    make_plots(plotting_params, args)
    print("Plotting is complete")

if __name__ == "__main__":
    main()



